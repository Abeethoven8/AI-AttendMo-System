function predictionMetric(
    array $metrics,
    $key,
    $default = null
) {
    return
        isset($metrics[$key])
        && $metrics[$key] !== ""
            ? $metrics[$key]
            : $default;
}


function predictionPercent($value)
{
    if (!is_numeric($value)) {
        return "—";
    }

    return number_format(
        ((float)$value) * 100,
        2
    ) . "%";
}


function predictionNumber($value)
{
    if (!is_numeric($value)) {
        return "—";
    }

    return number_format(
        (float)$value,
        4
    );
}


